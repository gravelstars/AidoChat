#!/usr/bin/env node
// 在新建的浏览器上下文中验收，不读取桌面数据或个人浏览器配置。
import { createRequire } from 'node:module'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const require = createRequire(new URL('../frontend/package.json', import.meta.url))
const { chromium } = require('playwright')
const base = process.argv[2] || 'http://127.0.0.1:4173/AidoChat/'
const output = process.env.DEMO_QA_DIR || '/tmp/aidochat-023-demo-qa'
await mkdir(output, {recursive:true})
const browser = await chromium.launch()
const report = { basePath:new URL(base).pathname, checks:[], externalRequests:[], failedRequests:[] }
try {
  const context = await browser.newContext({viewport:{width:1440,height:900},locale:'zh-CN',colorScheme:'light'})
  context.on('request', r => {
    if (!r.url().startsWith(new URL(base).origin) && !/^(data:|blob:)/.test(r.url())) report.externalRequests.push(r.url())
  })
  context.on('response', r => { if(r.status()>=400)report.failedRequests.push({url:r.url(),status:r.status()}) })
  const page = await context.newPage()
  await page.goto(base)
  await page.getByText('演示版：回复是预设内容，不会调用任何模型，数据只保存在你的浏览器里。',{exact:true}).waitFor()
  await page.getByRole('heading',{name:'首页改版评审',exact:true}).waitFor()
  await page.evaluate(()=>document.fonts.ready)
  const memory = page.getByRole('complementary',{name:'群纪要'})
  const proposal = memory.locator('[data-tone="user"]').first()
  const text = await proposal.locator('p').innerText()
  await proposal.getByRole('button',{name:'盖章',exact:true}).click()
  await memory.locator('[data-tone="confirmed"]').filter({hasText:text}).waitFor()
  await page.reload()
  await memory.locator('[data-tone="confirmed"]').filter({hasText:text}).waitFor()
  report.checks.push('首次示例群、盖章与刷新持久化')
  await page.getByRole('button',{name:'关闭演示提示',exact:true}).click()
  await page.getByRole('button',{name:'关闭试用提示',exact:true}).click()
  await page.getByRole('button',{name:'群管理',exact:true}).click()
  await page.getByRole('dialog').getByLabel('群名',{exact:true}).waitFor()
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
  await page.getByRole('button',{name:'新建群聊',exact:true}).click()
  await page.getByRole('dialog').getByLabel('群名',{exact:true}).waitFor()
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
  report.checks.push('新建群与群管理界面')
  await page.getByRole('button',{name:'分享图片',exact:true}).click()
  await page.getByRole('dialog').getByText(/仅预览/).waitFor()
  assert.equal(await page.getByRole('dialog').getByRole('button',{name:'保存图片',exact:true}).isEnabled(),false)
  await page.getByRole('dialog').getByRole('button',{name:'关闭',exact:true}).click()
  report.checks.push('起止消息分享界面与浏览器仅预览说明')
  await page.getByRole('button',{name:'成员',exact:true}).click()
  await page.getByRole('button',{name:'新建成员',exact:true}).waitFor()
  await page.getByRole('button',{name:'新建成员',exact:true}).click()
  for(const name of ['名字','模型服务','模型','角色提示词','图片输入'])await page.getByRole('dialog').getByLabel(name,{exact:true}).waitFor()
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
  report.checks.push('成员角色、自由模型名、图片能力与表单内服务入口')
  await page.getByRole('button',{name:'设置',exact:true}).click()
  for(const name of ['宣纸','素笺','麻纸','青笺','夜读','乌金'])await page.getByRole('radio',{name:new RegExp(`^${name}`)}).waitFor()
  await page.getByLabel('显示名',{exact:true}).waitFor()
  await page.getByRole('button',{name:'新建服务',exact:true}).click()
  assert.equal(await page.locator('input[type=password]').count(),0)
  assert.equal(await page.getByRole('button',{name:'测试连接',exact:true}).count(),0)
  await page.getByRole('dialog').getByRole('button',{name:'取消',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'在文件管理器中打开',exact:true}).count(),0)
  await page.screenshot({path:`${output}/settings-day.png`})
  report.checks.push('六纸、个人资料与真实凭证/连接/目录入口隔离')
  await page.getByRole('button',{name:'重置演示',exact:true}).click()
  await page.getByRole('heading',{name:'首页改版评审',exact:true}).waitFor()
  await page.getByText('演示版：回复是预设内容，不会调用任何模型，数据只保存在你的浏览器里。',{exact:true}).waitFor()
  await memory.locator('[data-tone="user"]').filter({hasText:text}).waitFor()
  report.checks.push('重置恢复虚构初始数据与提示')
  await page.locator('input[type="file"][accept*=".pdf"]').setInputFiles({name:'demo-note.txt',mimeType:'text/plain',buffer:Buffer.from('演示附件：只在浏览器里保存。')})
  await page.getByRole('list',{name:'待发送附件'}).getByText('demo-note.txt',{exact:true}).waitFor()
  await page.getByRole('textbox',{name:'消息',exact:true}).fill('附件记录')
  await page.getByRole('button',{name:'发送',exact:true}).click()
  await page.getByRole('list',{name:'消息附件'}).getByText('demo-note.txt',{exact:true}).waitFor()
  report.checks.push('实际文件输入与附件消息记录')
  await page.getByRole('textbox',{name:'消息',exact:true}).fill('@墨白 @青砚 讨论示例')
  await page.getByRole('button',{name:'发送',exact:true}).click()
  await page.getByRole('button',{name:'停止',exact:true}).waitFor()
  await page.getByRole('button',{name:'停止',exact:true}).click()
  await page.getByRole('button',{name:'发送',exact:true}).waitFor()
  report.checks.push('@点名、串行状态与停止')
  await page.getByRole('button',{name:'切换昼夜',exact:true}).click()
  await page.screenshot({path:`${output}/chat-night.png`})
  for(const width of [899,390]) {
    await page.setViewportSize({width,height:640})
    await page.getByRole('heading',{name:'这个应用为电脑设计，请用电脑打开'}).waitFor()
    assert.equal(await page.getByRole('navigation',{name:'群聊列表'}).count(),0)
    const image = page.getByRole('img',{name:/AidoChat 宣纸主题/})
    await image.scrollIntoViewIfNeeded()
    // Pages 首次冷加载比本地慢；等图片真正解码完成再断言，避免把加载中当成坏图。
    assert.equal(await image.evaluate(async el=>{
      if(!el.complete) await new Promise(resolve=>{el.addEventListener('load',resolve,{once:true});el.addEventListener('error',resolve,{once:true})})
      if(el.decode) await el.decode().catch(()=>{})
      return el.complete&&el.naturalWidth>0
    }),true)
    const link = page.getByRole('link',{name:'查看桌面版下载说明'})
    await link.scrollIntoViewIfNeeded()
    const box=await link.boundingBox();assert(box.y>=0&&box.y+box.height<=640)
    await page.screenshot({path:`${output}/mobile-${width}.png`})
  }
  report.checks.push('899px/390px手机说明、真实截图与可滚动下载入口')
  assert.equal(report.externalRequests.length,0)
  assert.equal(report.failedRequests.length,0)
  report.checks.push('所有字体图片脚本请求同源、子路径无404')
  await context.close()
  report.ok=true
} catch(error) {report.ok=false;report.error=String(error);throw error}
finally {await writeFile(`${output}/result.json`,JSON.stringify(report,null,2)+'\n');await browser.close()}
console.log(JSON.stringify(report,null,2))
